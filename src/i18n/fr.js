// "atténuation" (falloff), "suivi" (tracking), "surchauffe" (overheat). Left English on purpose:
// "fitting" and "rig", which French players say as loanwords and which the client does not usefully
// replace. Item names, damage types and unit symbols are never translated at all.
//
// A value may be a form MAP instead of a string where the phrase counts something. French takes the
// same two forms as English (with 0 taking `one`), so `one` and `other` are all that appear here.
